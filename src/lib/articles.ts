export const CUSTOM_STORAGE_KEY = "agrilink-custom-articles";
export const ADMIN_EMAIL = "admin@agrilink.demo";

export function isAdminEmail(value: string | null): boolean {
  return value?.toLowerCase() === ADMIN_EMAIL;
}

export function getCustomArticles(): Article[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = window.localStorage.getItem(CUSTOM_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as Article[];
    return Array.isArray(parsed) ? parsed.filter((a) => a && a.slug) : [];
  } catch {
    return [];
  }
}

export function saveCustomArticle(article: Article): Article[] {
  const existing = getCustomArticles().filter((a) => a.slug !== article.slug);
  const next = [{ ...article, custom: true }, ...existing];
  try {
    window.localStorage.setItem(CUSTOM_STORAGE_KEY, JSON.stringify(next));
  } catch {
    // storage full / private mode — ignore
  }
  return next;
}

export function deleteCustomArticle(slug: string): Article[] {
  const next = getCustomArticles().filter((a) => a.slug !== slug);
  try {
    window.localStorage.setItem(CUSTOM_STORAGE_KEY, JSON.stringify(next));
  } catch {
    // ignore
  }
  return next;
}

export function slugify(input: string): string {
  return (
    input
      .toLowerCase()
      .trim()
      .replace(/[^a-z0-9\u0900-\u097F\u0C00-\u0C7F\u0B80-\u0BFF\u0C80-\u0CFF\u0900-\u093F]+/g, "-")
      .replace(/-+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 60) || `article-${Date.now()}`
  );
}

export function allArticles(): Article[] {
  if (typeof window === "undefined") return ARTICLES;
  return [...getCustomArticles(), ...ARTICLES];
}

export function findArticle(slug: string): Article | undefined {
  return allArticles().find((a) => a.slug === slug);
}
